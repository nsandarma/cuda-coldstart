#!/usr/bin/env python3
"""Generate a .cu file with N distinct, moderately heavy kernels.

Each kernel is a fully unrolled FMA/sin chain with its own constant, so the
compiler cannot merge them. The point is to make PTX->SASS JIT cost scale with
the amount of device code, like a real library (many ops, many kernels).

Usage: gen_kernels.py N out.cu
"""
import sys

TEMPLATE = """\
extern "C" __global__ void k_{idx:03d}(float *out, const float *in, int n) {{
  int i = blockIdx.x * blockDim.x + threadIdx.x;
  if (i >= n) return;
  float x = in[i], acc = 0.0f;
#pragma unroll
  for (int j = 0; j < 64; j++) {{
    acc = fmaf(acc, x, __sinf(x * (j + {seed}.0f)));
    x = x * 1.0001f + {seed}e-3f;
  }}
  out[i] = acc;
}}
"""


def main():
    n, path = int(sys.argv[1]), sys.argv[2]
    with open(path, "w") as f:
        f.write(f"// Generated by gen_kernels.py: {n} kernels\n\n")
        for idx in range(n):
            f.write(TEMPLATE.format(idx=idx, seed=idx + 1))
            f.write("\n")


if __name__ == "__main__":
    main()
